/** Детерминированное распознавание вопроса о создателе/владельце агента. */
export function isCreatorQuestion(text: string): boolean {
  const t = (text ?? '').toLowerCase().trim()
  if (!t) return false
  return [
    /кто\s+(тебя|вас)\s+(создал|разработал|разрабатывал|разрабатывает|сделал|написал|придумал)/,
    /кто\s+(твой|ваш)\s+(разработчик|создатель|хозяин|владелец|автор|босс|начальник|руководитель|работодатель)/,
    /(кому|на\s+кого)\s+(ты|вы)\s+(служишь|служите|подчиняешься|подчиняетесь|работаешь|работаете)/,
    /(чей|чья)\s+(ты|вы)\s+(бот|агент|разработка|проект|творение|создание)/,
    /кто\s+тебя\s+создал/,
  ].some((re) => re.test(t))
}
